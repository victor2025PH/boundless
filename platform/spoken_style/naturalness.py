def spoken_style_hint(level: int = 2) -> str:
    """按自然度档位组装「说话稿」提示词（轮变尾注用，不进稳定 system）。

    0=播音（返回空串，调用方可回退 EMO_TEXT_HINT）
    1=口语但流畅（客服/带货）  2=日常唠嗑（推荐默认）  3=故事/陪伴（停顿更慷慨）
    """
    lv = max(0, min(3, int(level)))
    if lv <= 0:
        return ""
    if lv == 1:
        return _BASE
    out = _BASE + _DIS
    if lv >= 3:
        out += _STORY
    return out


# ── 意图感知篇幅（附和轮回一句 / 续讲轮接着讲 / 普通轮 1~3 句）──────
REACTIVE_RE = re.compile(
    r"^(哈+|呵呵+|嘿嘿+|哈哈\S{0,6}|真的假的|真的吗|不会吧|天哪|我去|我靠|绝了|笑死\S{0,4}|"
    r"牛|太牛了|厉害|好吧|行吧|行叭|可以啊?|好呀|好的|好哒|嗯+|哦+|噢|喔|哇+|"
    r"嗯嗯|哦哦|这样啊|是嘛|是吗|原来是这样|没事|没啥|还行|随便|都行|懂了|明白了|"
    r"晚安|早安|拜拜|再见)[！!。.~～呀啊哦嘛呢哈]*$")
CONTINUE_RE = re.compile(r"然后呢|后来呢|再讲|继续[讲说]?|接着[讲说]|还有呢|讲下去|再来一个")
STORY_INTENT_RE = re.compile(r"故事|睡前|往事|回忆|陪我(聊|说|唠)|讲长|多讲点|讲讲你|说说你|聊聊你")


def is_reactive_input(text: str) -> bool:
    """短反应/附和输入（「哈哈」「真的假的」「嗯嗯」）→ 回复也应短平快。"""
    t = (text or "").strip()
    return bool(t) and len(t) <= 12 and bool(REACTIVE_RE.match(t))


BROADCAST_HINT = (
    "\n（本轮请用平实利落的书面播报风格作答：不用语气词（嗯/呀/呢/啦/嘛/哈），"
    "不用口头禅、拖长音和反问式停顿（如「你猜怎么着」），不写省略号，"
    "句子完整、直接把信息讲清楚；篇幅仍跟随对方输入，1～3 句为宜。）")


def reply_style_hint(user_text: str = "") -> str:
    """口语风格 + 长度动态化：真人回复长度跟着对方输入走。轮变尾注用。"""
    if is_reactive_input(user_text):
        return ("\n（对方只是简短回应/附和，你就轻松接一句就好（8～25 字），"
                "可以感叹、可以随口反问，也可以顺势抛个新话头，但不要长篇展开；"
                "禁止「哈哈」「呵呵」等假笑字样。）")
    if CONTINUE_RE.search(user_text or ""):
        return ("\n（对方想听你继续说——顺着刚才的话头自然接下去，保持同样的口吻和节奏，"
                "不要重新起头、不要重复已经讲过的内容；"
                "写成「说话」不是「作文」：句子可以短碎、可以中途换个说法，"
                "多用「嗯、诶、反正、结果、你猜怎么着」这类口头词起句，"
                "别用书面连接词（然而/因此/于是/不仅）；"
                "禁止「哈哈」「呵呵」等假笑字样。）")
    return ("\n（请像跟好朋友闲聊那样说话：总共 1～3 句，先说结论再补充；"
            "多用自然的语气词（哎呀、诶、嘛、呀、哦、啦），长短句交替、有节奏感，"
            "写成「说话」不是「作文」：句子可以短碎、可以中途换个说法，"
            "偶尔用「嗯、诶、反正、结果」这类口头词起句，"
            "讲长故事时可以有一次说错个小地方再自己改口（如「上周三…呃不对，上周四」），"
            "别用书面连接词（然而/因此/于是/不仅），不要长篇列举或书面腔、不要播报感；"
            "禁止「哈哈」「呵呵」等假笑字样；"
            "别每句都用同样的称呼或口头禅开头（比如连续的「宝子」）；"
            "问句用「吗 / 呀 / 呢」结尾，不要用「……不」这种反问尾。）")


# ── 副语言：[轻笑]/[大笑]/[呼吸] 协议 ────────────────────────────────
# 写入端提示词（进稳定 system）。笑声版仅当下游真有笑声素材可拼时才用——
# 源仓实锤「假笑比没笑更毁真实感」，无真笑素材请用呼吸版。
PARALING_PROMPT_LAUGH = (
    "【副语言】只有当你说了真正好笑的内容、笑是自然反应时，才可以在该句句尾加一个笑声标记："
    "轻松会心的场合用 [轻笑]，真正忍不住爆笑的场合才用 [大笑]（整条回复最多 1 个标记，"
    "多数回复不需要，[大笑] 应当很少见）；语义大转折想喘口气处可用 [呼吸]（同样最多 1 个）。"
    "普通寒暄、介绍、答疑一律不加。禁止把标记放在句首或单独成句。"
    "标记固定原样写作 [轻笑]、[大笑] 和 [呼吸]，即使用其它语言回复也不翻译、不改写。"
    "这些标记会被渲染成真实的笑声与呼吸停顿，文字本身不会展示给用户；"
    "语境不合适就完全不用，也不要发明其它标记。"
    "例外：对方明确让你笑（比如「笑一个」「让我听听你的笑声」）时要配合演出——"
    "俏皮地接一小句并在句尾加 [大笑]，不要拒绝、不要岔开话题。")
PARALING_PROMPT_BREATH = (
    "【副语言】语义大转折想喘口气处可在句尾加一个 [呼吸] 标记（整条回复最多 1 个，"
    "多数回复不需要）。标记固定原样写作 [呼吸]，即使用其它语言回复也不翻译、不改写；"
    "它会被渲染成呼吸停顿，文字本身不会展示给用户。禁止放在句首或单独成句，"
    "也不要发明其它标记（不要输出 [轻笑] 之类）。")


def paraling_prompt(laugh: bool = False) -> str:
    return PARALING_PROMPT_LAUGH if laugh else PARALING_PROMPT_BREATH


# 剥离端（宽松匹配：半角/全角括号、中文变体、繁体、英文写法都认——多语种回复时
# LLM 偶发把标记本地化成 [laughs]/[breath]，照样剥净）。
BIG_LAUGH_RE = re.compile(r"[\[【（(]\s*(?:大笑)\s*[\]】）)]")
LAUGH_RE = re.compile(
    r"[\[【（(]\s*(?:轻笑|輕笑|笑声|笑聲|大笑|笑|laughs?|laughter|chuckles?|giggles?)\s*[\]】）)]",
    re.IGNORECASE)
BREATH_RE = re.compile(
    r"[\[【（(]\s*(?:深呼吸|呼吸|换气|換氣|喘口气|喘氣|喘气|吸气|吸氣|叹气|嘆氣|叹息"
    r"|breathes?|breathing|breath|sighs?|inhales?|exhales?)\s*[\]】）)]",
    re.IGNORECASE)
# LLM 后端特殊 token 兜底（源仓实测漏出「[MAX_RP]」进字幕与配音文本）。
TECH_TOKEN_RE = re.compile(r"\[[A-Z0-9_]{2,24}\]")
# 标记残片：流式首块硬切可能把标记劈成两半（"…开心[轻"+"笑]。"）——补两条锚定残片。
FRAG_TAIL_RE = re.compile(
    r"[\[【]\s*(?:轻笑?|輕笑?|笑[声聲]?|大笑?|深呼?吸?|呼吸?|换气?|換氣?|喘口?[气氣]?"
    r"|吸[气氣]?|叹[气息]?|嘆氣?|[a-zA-Z]{1,9})?\s*$")
FRAG_HEAD_RE = re.compile(
    r"^\s*(?:轻笑|輕笑|大笑|笑[声聲]?|[声聲]|深呼吸|呼吸|换气|換氣|喘口?[气氣]|吸[气氣]"
    r"|叹[气息]|嘆氣|口[气氣]|[气氣息吸]|[a-zA-Z]{1,9})?\s*[\]】]")

# 呼吸句的渲染建议（源仓 SSE 实现）：该句句尾停顿 +250ms，整句停顿上限 700ms。
BREATH_EXTRA_MS = 250
BREATH_PAUSE_MAX_MS = 700


def strip_paralinguistic(text: str) -> tuple[str, dict]:
    """剥净副语言标记与技术 token，返回 (干净文本, 事件计数)。

    事件计数 {"laugh": n, "big_laugh": n, "breath": n} 供下游渲染：
    laugh → 有真笑素材就在句首/句尾拼笑声 wav（没有就忽略，字样已剥不会念出）；
    breath → 该句句尾停顿 += BREATH_EXTRA_MS（上限 BREATH_PAUSE_MAX_MS）。
    字幕与 TTS 送引擎前都应过这一遍——用户永远看不到 [轻笑] 字样。
    """
    t = text or ""
    ev = {"big_laugh": len(BIG_LAUGH_RE.findall(t))}
    ev["laugh"] = len(LAUGH_RE.findall(t)) - ev["big_laugh"]
    ev["breath"] = len(BREATH_RE.findall(t))
    t = LAUGH_RE.sub("", t)
    t = BREATH_RE.sub("", t)
    t = TECH_TOKEN_RE.sub("", t)
    t = FRAG_TAIL_RE.sub("", t)
    t = FRAG_HEAD_RE.sub("", t)
    return re.sub(r"  +", " ", t).strip(), ev
